function serialize(workflow) {
  return `${JSON.stringify(workflow, null, 2)}\n`;
}

if (require.main === module) {
  const wf = build();
  fs.writeFileSync(OUT, serialize(wf));
  const codeNodes = wf.nodes.filter((n) => n.type === 'n8n-nodes-base.code').length;
  const notes = wf.nodes.filter((n) => n.type === 'n8n-nodes-base.stickyNote').length;
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${wf.nodes.length - notes} nodes (${codeNodes} Code nodes) and ${notes} notes, ${Object.keys(wf.connections).length} connection sources.`);
}

