// npm run build: writes n8n/lead-to-owner.workflow.json, ready to import into n8n.
// Every Code node is built from the tested files in src/, inlined through a tiny module loader with only the
// comment lines taken out, so the workflow runs the code the tests cover. test/n8n.test.js runs the built nodes.
// Edit src/ (or src/config.js) and rebuild; never edit the Code nodes in n8n.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(__dirname, 'lead-to-owner.workflow.json');

// ---------- bundling ----------

const source = (name) => fs.readFileSync(path.join(SRC, `${name}.js`), 'utf8').trim();

// The copy that goes into n8n: full-line comments and blank lines removed (the commented files are in src/).
const compact = (code) => code.split('\n').filter((line) => line.trim() !== '' && !line.trim().startsWith('//')).join('\n');
const depsOf = (code) => [...code.matchAll(/require\('\.\/([a-z]+)'\)/g)].map((m) => m[1]);

// The modules a Code node needs, dependencies first.
function closure(entries) {
  const order = [];
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    depsOf(source(name)).forEach(visit);
    order.push(name);
  };
  entries.forEach(visit);
  return order;
}

const LOADER = [
  '// ---- Library generated by n8n/build-workflow.js from src/ (commented source: src/*.js). Do not edit here. ----',
  'const __defs = {};',
  'const __cache = {};',
  'function __def(name, fn) { __defs[name] = fn; }',
  'function __req(name) {',
  "  const key = name.replace(/^\\.\\//, '').replace(/\\.js$/, '');",
  '  if (__cache[key]) return __cache[key].exports;',
  '  const module = { exports: {} };',
  '  __cache[key] = module;',
  '  __defs[key](module, module.exports, __req);',
  '  return module.exports;',
  '}',
].join('\n');

// Reads another node's first output item, or null when that node did not run in this execution.
const OUTPUT_HELPER = [
  'function output(name) {',
  '  try {',
  '    const node = $(name);',
  '    if (node.isExecuted === false) return null;',
  '    const item = node.first();',
  '    return item ? item.json : null;',
  '  } catch (err) {',
  '    return null;',
  '  }',
  '}',
].join('\n');

function bundle(modules) {
  const defs = closure(modules).map((name) => `// src/${name}.js\n__def('${name}', function (module, exports, require) {\n${compact(source(name))}\n});`);
  return `${LOADER}\n${defs.join('\n')}\n// ---- end of library ----`;
}

// ---------- node helpers ----------

const uuid = (seed) => {
  const h = crypto.createHash('sha1').update(`lead-to-owner:${seed}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const CREDS = {
  hubspot: { hubspotAppToken: { id: 'REPLACE_hubspot_token', name: 'HubSpot token (service key or private app)' } },
  anthropic: { httpHeaderAuth: { id: 'REPLACE_anthropic_key', name: 'Anthropic API key (header x-api-key)' } },
  slack: { httpHeaderAuth: { id: 'REPLACE_slack_bot', name: 'Slack bot token (header Authorization: Bearer xoxb-...)' } },
  intake: { httpHeaderAuth: { id: 'REPLACE_intake_secret', name: 'Lead intake secret (header X-Lead-Router-Key)' } },
  clayCallback: { httpHeaderAuth: { id: 'REPLACE_clay_callback_secret', name: 'Clay callback secret (header X-Clay-Callback-Key)' } },
};

const RETRY = { retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 };

// HubSpot's date-versioned API (the latest version when this was built). The request bodies are the same as v3.
const HS = 'https://api.hubapi.com';
