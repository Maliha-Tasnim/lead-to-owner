function node(name, type, typeVersion, position, parameters, extra = {}) {
  return { parameters, id: uuid(name), name, type, typeVersion, position, ...extra };
}

// The node's own few lines come first, inside main(), so they are what you see when you open the node.
// The generated library follows; main() runs once everything is defined.
function code(name, position, modules, body) {
  const own = body.trim();
  const needsOutput = /\boutput\(/.test(own);
  if (!modules.length && !needsOutput) return node(name, 'n8n-nodes-base.code', 2, position, { jsCode: `${own}\n` });
  const indented = own.split('\n').map((line) => (line ? `  ${line}` : line)).join('\n');
  const parts = [`async function main() {\n${indented}\n}`];
  if (needsOutput) parts.push(OUTPUT_HELPER);
  if (modules.length) parts.push(bundle(modules));
  parts.push('return main();');
  return node(name, 'n8n-nodes-base.code', 2, position, { jsCode: `${parts.join('\n\n')}\n` });
}

function http(name, position, { method = 'POST', url, body, auth, headers, onError, timeout = 15000, retry = true }) {
  const parameters = { method, url };
  if (auth === 'hubspot') {
    parameters.authentication = 'predefinedCredentialType';
    parameters.nodeCredentialType = 'hubspotAppToken';
  } else if (auth) {
    parameters.authentication = 'genericCredentialType';
    parameters.genericAuthType = 'httpHeaderAuth';
  }
  if (headers) {
    parameters.sendHeaders = true;
    parameters.headerParameters = { parameters: Object.entries(headers).map(([n, value]) => ({ name: n, value })) };
  }
  if (body) {
    parameters.sendBody = true;
    parameters.specifyBody = 'json';
    parameters.jsonBody = body;
  }
  parameters.options = { timeout };
  const extra = {};
  if (auth) extra.credentials = CREDS[auth];
  if (retry) Object.assign(extra, RETRY);
  if (onError) extra.onError = onError;
  return node(name, 'n8n-nodes-base.httpRequest', 4.2, position, parameters, extra);
}

function ifNode(name, position, leftValue) {
  return node(name, 'n8n-nodes-base.if', 2, position, {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
      conditions: [{ id: uuid(`${name}:condition`), leftValue, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
      combinator: 'and',
    },
    options: {},
  });
}

function sticky(key, position, width, height, content, color) {
  return node(`Note: ${key}`, 'n8n-nodes-base.stickyNote', 1, position, { content, height, width, ...(color ? { color } : {}) });
}

const slackPost = (name, position) => http(name, position, {
  url: 'https://slack.com/api/chat.postMessage',
  auth: 'slack',
  body: '={{ JSON.stringify({ channel: $json.channel, text: $json.text, unfurl_links: false }) }}',
});

// Slack answers errors with HTTP 200 and ok: false, so a failed post would pass silently without this check.
const slackCheck = (name, position) => code(name, position, [], `
const failed = $input.all().filter((item) => item.json.ok !== true);
if (failed.length) throw new Error(\`Slack did not accept \${failed.length} message(s): \${failed.map((item) => item.json.error || 'no reason given').join(', ')}\`);
return [];`);

